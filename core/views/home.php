<script>
    document.addEventListener('DOMContentLoaded', function() {
        carregarItens(); // carrega todos por padrão

        function carregarItens(categoria = null) {
            const url = categoria ? `?a=carregar_cardapio&categoria=${categoria}` : '?a=carregar_cardapio';

            fetch(url)
                .then(res => res.json())
                .then(data => {
                    const containerItens = document.getElementById('lista-cardapio');
                    const containerCategorias = document.getElementById('filtros-categorias');

                    // Renderizar categorias
                    let categoriasHTML = `<li data-filter="*" class=""><a href="#">Todos</a></li>`;
                    data.categorias.forEach(cat => {
                        categoriasHTML += `<li data-filter=".${cat}"><a href="#">${cat.charAt(0).toUpperCase() + cat.slice(1)}</a></li>`;
                    });
                    containerCategorias.innerHTML = categoriasHTML;

                    // Renderizar itens
                    containerItens.innerHTML = '';
                    data.itens.forEach(item => {
                        const itemHTML = `
                        <div class="col-lg-6 menu-item isotope-item ${item.categoria}">
                            <img src="assets/img/menu/${item.imagem}" class="menu-img" alt="${item.imagem}">
                            <div class="menu-content">
                                <a href="#">${item.nome_item}</a><span>${item.preco}</span>
                            </div>
                            <div class="menu-ingredients">
                                ${item.descricao}
                            </div>
                            <div class="menu-ingredients mt-2">
                                <button class="btn btn-info btn-sm" onclick="adicionar_carrinho(${item.id_item})">
                                    <i class="fas fa-shopping-cart me-2"></i>Fazer Pedido
                                </button>
                            </div>
                        </div>
                    `;
                        containerItens.insertAdjacentHTML('beforeend', itemHTML);
                    });

                    // Atualiza filtros
                    if (typeof Isotope !== 'undefined') {
                        const iso = new Isotope('.isotope-container', {
                            itemSelector: '.menu-item',
                            layoutMode: 'masonry'
                        });

                        document.querySelectorAll('.menu-filters li').forEach(filtro => {
                            filtro.addEventListener('click', function(e) {
                                e.preventDefault();
                                document.querySelectorAll('.menu-filters li').forEach(el => el.classList.remove('filter-active'));
                                this.classList.add('filter-active');
                                const cat = this.getAttribute('data-filter').replace('.', '');
                                if (cat === '*') {
                                    carregarItens(); // todos
                                } else {
                                    carregarItens(cat); // por categoria
                                }
                            });
                        });
                    }
                })
                .catch(err => console.error('Erro ao buscar itens:', err));
        }
    });
</script>